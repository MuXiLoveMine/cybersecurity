#!/bin/bash
# 05_case.sh
# case 多分支示例

echo "=========================================="
echo "1. 简单的数字菜单"
echo "=========================================="

read -p "请输入一个数字（1-3）：" num

case $num in
    1)
        echo "你选择了 1"
        echo "执行操作一..."
        ;;
    2)
        echo "你选择了 2"
        echo "执行操作二..."
        ;;
    3)
        echo "你选择了 3"
        echo "执行操作三..."
        ;;
    *)
        echo "无效输入"
        exit 1
        ;;
esac

echo ""
echo "=========================================="
echo "2. 文件类型判断"
echo "=========================================="

read -p "请输入一个文件名：" filename

case $filename in
    *.txt|*.md|*.log)
        echo "这是文本文件"
        ;;
    *.sh|*.bash)
        echo "这是 Shell 脚本"
        ;;
    *.jpg|*.png|*.gif|*.bmp)
        echo "这是图片文件"
        ;;
    *.tar.gz|*.tgz|*.zip|*.rar|*.7z)
        echo "这是压缩文件"
        ;;
    [a-z]*)
        echo "文件名以小写字母开头"
        ;;
    *)
        echo "其他类型的文件"
        ;;
esac

echo ""
echo "=========================================="
echo "3. 服务管理菜单"
echo "=========================================="

PS3="请选择操作："
select action in "启动服务" "停止服务" "重启服务" "查看状态" "退出"; do
    case $action in
        "启动服务")
            echo "正在启动服务..."
            ;;
        "停止服务")
            echo "正在停止服务..."
            ;;
        "重启服务")
            echo "正在重启服务..."
            ;;
        "查看状态")
            echo "服务运行中"
            ;;
        "退出")
            echo "再见！"
            break
            ;;
        *)
            echo "无效选项"
            ;;
    esac
done
