#!/bin/bash
# template.sh
# Shell 脚本模板 - 可作为新脚本的起点
# 使用方法：复制此文件，修改功能描述和主逻辑

set -euo pipefail

# ============================================================
# 脚本信息
# ============================================================
readonly SCRIPT_NAME=$(basename "$0")
readonly SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
readonly SCRIPT_VERSION="1.0.0"

# ============================================================
# 颜色定义
# ============================================================
readonly RED='\033[0;31m'
readonly GREEN='\033[0;32m'
readonly YELLOW='\033[1;33m'
readonly BLUE='\033[0;34m'
readonly NC='\033[0m' # No Color

# ============================================================
# 日志函数
# ============================================================
log_info()    { echo -e "${GREEN}[INFO]${NC}  $*"; }
log_warn()    { echo -e "${YELLOW}[WARN]${NC}  $*" >&2; }
log_error()   { echo -e "${RED}[ERROR]${NC} $*" >&2; }
log_debug()   { [[ "${DEBUG:-0}" == "1" ]] && echo -e "${BLUE}[DEBUG]${NC} $*"; }

# ============================================================
# 使用说明
# ============================================================
usage() {
    cat << EOF
用法：$SCRIPT_NAME [选项] <参数>

描述：
  脚本功能简介

选项：
  -h, --help          显示此帮助信息
  -v, --version       显示版本号
  -d, --debug         启用调试模式
  -n, --name <名称>   指定名称（示例参数）
  -o, --output <文件> 指定输出文件

示例：
  $SCRIPT_NAME -n test -o result.txt
  $SCRIPT_NAME --debug --name hello

EOF
    exit 0
}

# ============================================================
# 版本信息
# ============================================================
version() {
    echo "$SCRIPT_NAME v$SCRIPT_VERSION"
    exit 0
}

# ============================================================
# 清理函数
# ============================================================
cleanup() {
    log_debug "执行清理操作..."
    # 在这里添加清理逻辑
    # rm -f "$TEMP_FILE"
    log_debug "清理完成"
}
trap cleanup EXIT

# ============================================================
# 参数解析
# ============================================================
NAME=""
OUTPUT_FILE=""

parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            -h|--help)
                usage
                ;;
            -v|--version)
                version
                ;;
            -d|--debug)
                DEBUG=1
                set -x
                shift
                ;;
            -n|--name)
                NAME="$2"
                shift 2
                ;;
            -o|--output)
                OUTPUT_FILE="$2"
                shift 2
                ;;
            --)
                shift
                break
                ;;
            -*)
                log_error "未知选项：$1"
                usage
                ;;
            *)
                # 位置参数
                PARAMS+=("$1")
                shift
                ;;
        esac
    done
}

# ============================================================
# 参数校验
# ============================================================
validate_args() {
    if [[ -z "$NAME" ]]; then
        log_error "必须指定名称（--name）"
        usage
    fi
}

# ============================================================
# 主逻辑函数
# ============================================================
main_logic() {
    log_info "脚本开始执行"
    log_info "名称：$NAME"
    [[ -n "$OUTPUT_FILE" ]] && log_info "输出文件：$OUTPUT_FILE"
    log_info "脚本目录：$SCRIPT_DIR"

    # ===== 在这里编写主要逻辑 =====

    log_info "脚本执行完成"
}

# ============================================================
# 入口
# ============================================================
main() {
    parse_args "$@"
    validate_args
    main_logic
}

main "$@"
