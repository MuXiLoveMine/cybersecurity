class 数据脱敏工具:
    """
    数据脱敏工具

    功能说明：
        - 掩码脱敏 - 部分字符替换为*
        - 替换脱敏 - 用虚拟值替换真实数据
        - 加密脱敏 - 可逆加密后存储
        - 哈希脱敏 - 不可逆哈希处理
        - 格式保留脱敏 - 保持数据格式但替换内容
        - 数据扰动 - 对数值添加随机偏移

    技术原理：
        数据脱敏是保护敏感数据的重要手段，在开发/测试环境
        中使用脱敏数据代替真实数据。根据使用场景选择不同方法：

        - 静态脱敏: 一次性处理批量数据
        - 动态脱敏: 实时根据用户权限动态脱敏

        脱敏方法选择原则：
        - 开发测试: 掩码或替换（不可逆）
        - 数据分析: 哈希或扰动（不可逆）
        - 合规存储: 加密脱敏（可逆，需密钥管理）
    """

    def __init__(self):
        self.脱敏记录 = []
        print("[初始化] 数据脱敏工具已就绪")

    def 掩码脱敏(self, 数据: str, 数据类型: str) -> str:
        """
        掩码脱敏 - 将部分字符替换为*

        技术说明：
            掩码脱敏保留数据格式的关键部分，隐藏中间敏感内容。
            不同的数据类型使用不同的掩码规则：
            - 手机号: 保留前3后4，中间掩码 (138****8000)
            - 身份证号: 保留前4后4 (1101********1234)
            - 银行卡号: 保留前4后4 (6222********5678)
            - 邮箱: 保留首字母和域名 (a***@example.com)
            - 姓名: 保留姓 (张**)
        """
        print(f"\n  [掩码脱敏] 类型={数据类型}, 原始={数据}")

        if 数据类型 == "手机号":
            # 保留前3后4
            结果 = 数据[:3] + "*" * 4 + 数据[-4:]

        elif 数据类型 == "身份证号":
            # 保留前4后4
            结果 = 数据[:4] + "*" * (len(data) - 8) + 数据[-4:]

        elif 数据类型 == "银行卡号":
            # 保留前4后4
            结果 = data[:4] + "*" * (len(data) - 8) + data[-4:]

        elif 数据类型 == "邮箱":
            # 保留首字母和域名
            if "@" in data:
                用户名, 域名 = data.split("@")
                结果 = 用户名[0] + "***@" + 域名
            else:
                结果 = data[0] + "***"

        elif 数据类型 == "姓名":
            # 保留姓
            if len(data) <= 1:
                结果 = data
            elif len(data) == 2:
                结果 = data[0] + "*"
            else:
                结果 = data[0] + "*" * (len(data) - 2) + data[-1]

        else:
            # 默认: 保留首尾各1/3
            保留 = max(1, len(data) // 3)
            结果 = data[:保留] + "*" * (len(data) - 2 * 保留) + data[-保留:]

        print(f"             结果={结果}")
        self.脱敏记录.append(("掩码", 数据类型, 数据, 结果))
        return 结果

