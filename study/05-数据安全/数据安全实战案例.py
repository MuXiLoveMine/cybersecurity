class 数据资产发现与分类器:
    """
    数据资产发现与分类工具

    功能说明：
        - 扫描数据库表结构，识别敏感字段
        - 扫描文件系统，发现含敏感数据的文件
        - 根据分类标准对数据进行分级
        - 生成数据资产清单

    技术原理：
        数据资产发现是数据安全的基础。通过扫描数据存储位置，
        识别哪些数据是敏感的，并进行分类分级。

        常见敏感数据类型：
        - 个人身份信息(PII): 姓名、身份证号、手机号
        - 金融信息: 银行卡号、CVV、交易金额
        - 凭据信息: 密码、密钥、Token
        - 敏感配置: 数据库连接串、API密钥
        - 健康信息: 病历、体检报告

        发现方法：
        - 数据库: 查询information_schema元数据
        - 文件系统: 正则表达式匹配敏感模式
        - 网络: DPI深度包检测
    """

    # 敏感字段名匹配规则
    敏感字段规则 = {
        "密码": ["password", "passwd", "pwd", "secret", "credential"],
        "身份证号": ["idcard", "id_card", "identity", "cert_no"],
        "手机号": ["phone", "mobile", "telephone", "cellphone"],
        "银行卡号": ["bank_card", "card_no", "card_number", "account_no"],
        "邮箱": ["email", "mail", "mailbox"],
        "姓名": ["realname", "full_name", "name", "username"],
        "地址": ["address", "addr", "location"],
        "薪资": ["salary", "wage", "income", "compensation"],
        "IP地址": ["ip", "ip_address", "client_ip"],
        "API密钥": ["api_key", "apikey", "access_key", "secret_key"],
    }

    # 敏感数据正则模式
    敏感数据正则 = {
        "身份证号": r'[1-9]\d{5}(19|20)\d{2}(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])\d{3}[\dXx]',
        "手机号": r'1[3-9]\d{9}',
        "银行卡号": r'6\d{15,18}',
        "邮箱": r'[\w.+-]+@[\w-]+\.[\w.-]+',
        "IP地址": r'\b(?:\d{1,3}\.){3}\d{1,3}\b',
        "API密钥": r'(?:api_key|secret|password|token)\s*[=:]\s*["\']([^"\']+)["\']',
    }

    def __init__(self):
        self.资产清单 = []
        self.敏感数据计数 = defaultdict(int)
        print("[初始化] 数据资产发现与分类器已就绪")

    def 扫描数据库(self, 数据库表: List[Dict] = 模拟数据库表):
        """
        扫描数据库表结构，识别敏感字段

        技术说明：
            通过查询数据库元数据(information_schema)获取表结构，
            然后根据字段名匹配敏感数据。

            MySQL查询示例：
            SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE
            FROM information_schema.COLUMNS
            WHERE TABLE_SCHEMA = 'user_db';
        """
        print("\n" + "=" * 70)
        print("数据资产发现 - 数据库扫描")
        print("=" * 70)
        print(f"  扫描数据库: {len(数据库表)} 个表\n")

        for 表 in 数据库表:
            库名 = 表["库名"]
            表名 = 表["表名"]
            字段列表 = 表["字段"]

            print(f"  [{库名}.{表名}] ({len(字段列表)} 个字段)")

            敏感字段数 = 0
            for 字段 in 字段列表:
                名称 = 字段["名称"]
                类型 = 字段["类型"]
                敏感 = 字段.get("敏感", False)
                分类 = 字段.get("分类", "未分类")

                if 敏感:
                    敏感字段数 += 1
                    等级 = self._获取分类等级(分类)
                    print(f"    [!!] {名称:25s} {类型:20s} [{分类}] 等级{等级}")

                    self.资产清单.append({
                        "来源": f"{库名}.{表名}",
                        "字段": 名称,
                        "类型": 类型,
                        "分类": 分类,
                        "等级": 等级,
                    })
                    self.敏感数据计数[分类] += 1
                else:
                    print(f"    [OK] {名称:25s} {类型}")

            print(f"    -> 敏感字段: {敏感字段数}/{len(字段列表)}\n")

    def _获取分类等级(self, 分类: str) -> int:
        """获取数据分类的安全等级"""
        for 类别, 配置 in 数据分类标准.items():
            if 分类 in 类别 or 类别 in 分类:
                return 配置["等级"]
        return 2

    def 扫描文件系统(self, 文件列表: List[Dict] = 模拟文件系统):
        """
        扫描文件系统，发现含敏感数据的文件

        技术说明：
            文件系统扫描通过以下方式发现敏感数据：
            1. 文件名匹配 - 包含password/secret/config等关键词
            2. 文件内容扫描 - 使用正则表达式匹配敏感数据模式
            3. 文件类型识别 - 配置文件、备份文件、CSV等
            4. 内容指纹 - 与已知敏感数据模式匹配

            常见敏感文件位置：
            - /data/config/ - 配置文件
            - /data/backup/ - 备份文件
            - /data/uploads/ - 上传文件
            - .env / .git / .ssh - 隐藏配置
        """
        print("=" * 70)
        print("数据资产发现 - 文件系统扫描")
        print("=" * 70)
        print(f"  扫描路径: /data/")
        print(f"  扫描文件: {len(文件列表)} 个\n")

        for f in 文件列表:
            路径 = f["路径"]
            大小 = f["大小"]
            含敏感 = f["含敏感"]
            内容 = f["内容"]

            标识 = "[!!]" if 含敏感 else "[OK]"
            print(f"  {标识} {路径}")
            print(f"      大小: {self._格式化大小(大小)}")

            if 含敏感:
                # 检测文件中的敏感数据类型
                发现类型 = []
                for 数据类型, 正则 in self.敏感数据正则.items():
                    匹配 = re.findall(正则, 内容)
                    if 匹配:
                        发现类型.append(数据类型)
                        self.敏感数据计数[数据类型] += len(匹配)

                if 发现类型:
                    print(f"      敏感数据类型: {', '.join(发现类型)}")
                else:
                    print(f"      敏感关键词匹配")

                self.资产清单.append({
                    "来源": 路径,
                    "字段": "文件内容",
                    "类型": "文件",
                    "分类": "文件存储",
                    "等级": 4 if 含敏感 else 2,
                })
            print()

    def _格式化大小(self, 大小: int) -> str:
        """格式化文件大小"""
        if 大小 < 1024:
            return f"{大小}B"
        elif 大小 < 1024 * 1024:
            return f"{大小/1024:.1f}KB"
        else:
            return f"{大小/1024/1024:.1f}MB"

    def 生成资产清单(self):
        """生成数据资产清单报告"""
        print("\n" + "=" * 70)
        print("数据资产清单报告")
        print("=" * 70)

        print(f"\n  资产总数: {len(self.资产清单)}")
        print(f"\n  敏感数据分布:")
        for 类型, 数量 in sorted(self.敏感数据计数.items(), key=lambda x: -x[1]):
            print(f"    {类型:15s}: {数量} 处")

        # 按等级统计
        等级统计 = defaultdict(int)
        for 资产 in self.资产清单:
            等级统计[资产["等级"]] += 1

        print(f"\n  安全等级分布:")
        for 等级 in sorted(等级统计.keys()):
            标识 = {1: "公开", 2: "内部", 3: "个人信息", 4: "敏感信息", 5: "机密数据"}
            名称 = 标识.get(等级, "未知")
            print(f"    等级{等级} ({名称}): {等级统计[等级]} 个")

        print(f"\n  分类建议:")
        print("    1. 对等级4-5的数据实施加密存储")
        print("    2. 对等级3的数据实施访问控制")
        print("    3. 对所有敏感数据建立访问审计")
        print("    4. 定期扫描确保新数据被正确分类")

        return {
            "资产总数": len(self.资产清单),
            "敏感数据分布": dict(self.敏感数据计数),
            "等级统计": dict(等级统计)
        }


