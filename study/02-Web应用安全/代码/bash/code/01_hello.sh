#!/bin/bash
# ============================================================
# 01_hello.sh - Hello World 与脚本基础
# ============================================================

# 1. 最简单的输出
echo "Hello, World!"

# 2. 带格式的输出
echo "=============================="
echo "  欢迎学习 Bash 脚本编程"
echo "=============================="

# 3. 使用 printf 格式化输出
printf "姓名: %s\n年龄: %d\n" "张三" 25

# 4. 多行输出（使用 cat 和 here document）
cat << 'EOF'
========================================
  这是一个多行文本输出示例
  使用 here document 语法
  可以输出大段文本而无需多个 echo
========================================
EOF

# 5. 显示脚本信息
echo ""
echo "脚本名称: $0"
echo "当前 Shell: $SHELL"
echo "当前用户: $USER"
echo "当前目录: $PWD"
