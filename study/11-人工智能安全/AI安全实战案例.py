        print(f"  TNR (真负率): {sum(1 for d in 测试数据 if d['loss'] >= 阈值)/len(测试数据):.4f}")
        print(f"  隐私泄露风险: {'高' if 准确率 > 0.7 else '中' if 准确率 > 0.55 else '低'}")

