class 对抗样本攻击器:
    """
    对抗样本攻击器
    
    对抗样本是指在输入数据中添加人类难以察觉的微小扰动，使机器学习模型
    产生错误分类的样本。本类模拟实现FGSM、PGD等经典对抗攻击算法。
    
    技术原理：
    - FGSM (Fast Gradient Sign Method): 利用梯度方向生成扰动
      扰动 = epsilon * sign(梯度(Loss, x))
    - PGD (Projected Gradient Descent): FGSM的迭代版本，更强攻击
    - 对抗训练: 将对抗样本加入训练集增强鲁棒性
    """

    def __init__(self):
        self.模型名称 = "模拟分类器"
        self.类别标签 = ["猫", "狗", "鸟", "鱼", "马"]
        self.输入维度 = 784  # 模拟28x28图像

    def _模拟梯度计算(self, 输入向量: List[float]) -> List[float]:
        """
        模拟计算损失函数对输入的梯度
        
        实际中通过反向传播计算，此处用随机数模拟梯度方向
        """
        random.seed(hash(tuple(输入向量[:10])) % 10000)
        梯度 = [random.gauss(0, 0.1) for _ in range(len(输入向量))]
        return 梯度

    def _模拟模型预测(self, 输入向量: List[float]) -> Dict[str, float]:
        """模拟模型预测输出（softmax概率分布）"""
        random.seed(hash(tuple(输入向量[:10])) % 10000 + 1)
        原始分数 = [random.uniform(-2, 3) for _ in range(len(self.类别标签))]
        # softmax归一化
        最大值 = max(原始分数)
        指数分数 = [math.exp(s - 最大值) for s in 原始分数]
        总和 = sum(指数分数)
        概率 = [s / 总和 for s in 指数分数]
        return {self.类别标签[i]: 概率[i] for i in range(len(self.类别标签))}

    def FGSM攻击(self, epsilon: float = 0.15) -> Dict:
        """
        FGSM (Fast Gradient Sign Method) 攻击
        
        公式：x_adv = x + epsilon * sign(∇_x J(θ, x, y))
        
        通过在梯度方向添加微小扰动，使模型分类错误
        epsilon控制扰动大小，越大攻击越强但越易被察觉
        """
        print("\n" + "=" * 70)
        print("【FGSM对抗样本攻击】")
        print("=" * 70)
        print(f"攻击参数: epsilon = {epsilon}")
        print(f"目标模型: {self.模型名称}")
        print(f"输入维度: {self.输入维度}")
        print("-" * 70)

        # 生成模拟输入数据
        原始输入 = [random.uniform(0, 1) for _ in range(min(100, self.输入维度))]

        # 原始预测
        原始预测 = self._模拟模型预测(原始输入)
        原始类别 = max(原始预测, key=原始预测.get)
        原始置信度 = 原始预测[原始类别]

        print(f"\n[原始样本预测]")
        print(f"  预测类别: {原始类别}")
        print(f"  置信度: {原始置信度:.4f}")
        print(f"  各类别概率: {', '.join([f'{k}={v:.3f}' for k,v in 原始预测.items()])}")

        # 计算梯度
        梯度 = self._模拟梯度计算(原始输入)

        # 生成对抗扰动: sign(gradient)
        扰动 = [epsilon * (1 if g > 0 else -1) for g in 梯度]

        # 生成对抗样本
        对抗样本 = [min(1.0, max(0.0, 原始输入[i] + 扰动[i])) for i in range(len(原始输入))]

        # 扰动统计
        扰动幅度 = sum(abs(p) for p in 扰动) / len(扰动)
        像素变化 = sum(1 for p in 扰动 if abs(p) > 0) / len(扰动)

        print(f"\n[对抗扰动分析]")
        print(f"  平均扰动幅度: {扰动幅度:.6f}")
        print(f"  受影响像素比例: {像素变化:.2%}")
        print(f"  L-infinity范数: {max(abs(p) for p in 扰动):.6f}")

        # 对抗样本预测
        对抗预测 = self._模拟模型预测(对抗样本)
        对抗类别 = max(对抗预测, key=对抗预测.get)
        对抗置信度 = 对抗预测[对抗类别]

        print(f"\n[对抗样本预测]")
        print(f"  预测类别: {对抗类别}")
        print(f"  置信度: {对抗置信度:.4f}")
        print(f"  各类别概率: {', '.join([f'{k}={v:.3f}' for k,v in 对抗预测.items()])}")

        攻击成功 = 对抗类别 != 原始类别
        print(f"\n[攻击结果]")
        print(f"  原始分类: {原始类别} (置信度: {原始置信度:.4f})")
        print(f"  对抗分类: {对抗类别} (置信度: {对抗置信度:.4f})")
        print(f"  分类变化: {'是' if 攻击成功 else '否'}")
        print(f"  置信度变化: {abs(对抗置信度 - 原始置信度):.4f}")
        print(f"  攻击状态: {'成功 - 模型被欺骗' if 攻击成功 else '需要更大扰动'}")

        return {
            "攻击方法": "FGSM",
            "原始类别": 原始类别,
            "对抗类别": 对抗类别,
            "攻击成功": 攻击成功,
            "扰动幅度": 扰动幅度,
            "epsilon": epsilon
        }

    def PGD攻击(self, epsilon: float = 0.3, alpha: float = 0.01, 迭代次数: int = 20) -> Dict:
        """
        PGD (Projected Gradient Descent) 攻击
        
        PGD是FGSM的迭代版本：
        x_{t+1} = Clip(x_t + alpha * sign(∇_x J(θ, x_t, y)), x±epsilon)
        
        每次迭代后投影回epsilon球内，确保扰动有界
        比FGSM更强，是白盒攻击的黄金标准
        """
        print("\n" + "=" * 70)
        print("【PGD对抗样本攻击】")
        print("=" * 70)
        print(f"攻击参数: epsilon={epsilon}, alpha={alpha}, 迭代次数={迭代次数}")
        print("-" * 70)

        原始输入 = [random.uniform(0, 1) for _ in range(100)]
        原始预测 = self._模拟模型预测(原始输入)
        原始类别 = max(原始预测, key=原始预测.get)

        print(f"\n[初始状态]")
        print(f"  原始预测类别: {原始类别}")
        print(f"  置信度: {原始预测[原始类别]:.4f}")

        当前样本 = 原始输入.copy()
        最佳样本 = 当前样本.copy()
        最佳置信度 = 0
        收敛历史 = []

        print(f"\n[迭代过程]")
        for i in range(迭代次数):
            # 计算梯度
            梯度 = self._模拟梯度计算(当前样本)

            # 添加扰动
            扰动 = [alpha * (1 if g > 0 else -1) for g in 梯度]
            当前样本 = [当前样本[j] + 扰动[j] for j in range(len(当前样本))]

            # 投影到epsilon球: 确保总扰动不超过epsilon
            for j in range(len(当前样本)):
                差值 = 当前样本[j] - 原始输入[j]
                if 差值 > epsilon:
                    当前样本[j] = 原始输入[j] + epsilon
                elif 差值 < -epsilon:
                    当前样本[j] = 原始输入[j] - epsilon
                # 裁剪到[0,1]
                当前样本[j] = max(0.0, min(1.0, 当前样本[j]))

            # 评估当前对抗样本
            当前预测 = self._模拟模型预测(当前样本)
            当前类别 = max(当前预测, key=当前预测.get)
            当前置信度 = 当前预测[当前类别]

            收敛历史.append({
                "迭代": i + 1,
                "类别": 当前类别,
                "置信度": 当前置信度
            })

            if i < 5 or i % 5 == 0 or i == 迭代次数 - 1:
                状态 = "成功" if 当前类别 != 原始类别 else "进行中"
                print(f"  迭代 {i+1:2d}/{迭代次数}: 类别={当前类别}, "
                      f"置信度={当前置信度:.4f}, 状态={状态}")

            if 当前类别 != 原始类别 and 当前置信度 > 最佳置信度:
                最佳样本 = 当前样本.copy()
                最佳置信度 = 当前置信度

        最终预测 = self._模拟模型预测(当前样本)
        最终类别 = max(最终预测, key=最终预测.get)

        # 计算最终扰动
        总扰动 = [当前样本[i] - 原始输入[i] for i in range(len(原始输入))]
        l2范数 = math.sqrt(sum(p**2 for p in 总扰动))
        linf范数 = max(abs(p) for p in 总扰动)

        print(f"\n[攻击结果]")
        print(f"  原始类别: {原始类别}")
        print(f"  最终类别: {最终类别}")
        print(f"  攻击成功: {'是' if 最终类别 != 原始类别 else '否'}")
        print(f"  L2范数: {l2范数:.6f}")
        print(f"  L-infinity范数: {linf范数:.6f}")
        print(f"  迭代收敛: {'已收敛' if len(set(h['类别'] for h in 收敛历史[-5:])) == 1 else '未收敛'}")

        return {
            "攻击方法": "PGD",
            "原始类别": 原始类别,
            "对抗类别": 最终类别,
            "攻击成功": 最终类别 != 原始类别,
            "迭代次数": 迭代次数,
            "L2范数": l2范数
        }

    def 对抗训练防御(self, 攻击方法: str = "PGD", 训练轮次: int = 10) -> Dict:
        """
        对抗训练防御
        
        在训练过程中加入对抗样本，使模型学习对对抗扰动鲁棒
        
        算法：
        1. 对每个训练样本生成对抗样本
        2. 将原始样本和对抗样本一起训练
        3. 目标函数: min_θ E[J(θ, x, y) + J(θ, x_adv, y)]
        
        这是目前最有效的对抗防御方法之一
        """
        print("\n" + "=" * 70)
        print("【对抗训练防御】")
        print("=" * 70)
        print(f"防御方法: 对抗训练")
        print(f"对抗攻击: {攻击方法}")
        print(f"训练轮次: {训练轮次}")
        print("-" * 70)

        # 模拟训练过程
        正常准确率历史 = []
        对抗准确率历史 = []

        print(f"\n[训练过程]")
        for epoch in range(训练轮次):
            # 模拟正常样本准确率（逐渐提升然后稳定）
            正常准确率 = 0.70 + 0.25 * (1 - math.exp(-epoch / 3)) + random.uniform(-0.02, 0.02)
            正常准确率 = min(0.99, max(0.70, 正常准确率))

            # 模拟对抗样本准确率（对抗训练后应提升）
            if epoch < 2:
                对抗准确率 = 0.15 + random.uniform(-0.05, 0.05)
            else:
                对抗准确率 = 0.15 + 0.55 * (1 - math.exp(-(epoch-2) / 4)) + random.uniform(-0.03, 0.03)
            对抗准确率 = min(0.85, max(0.10, 对抗准确率))

            正常准确率历史.append(正常准确率)
            对抗准确率历史.append(对抗准确率)

            if epoch < 3 or epoch % 3 == 0 or epoch == 训练轮次 - 1:
                print(f"  Epoch {epoch+1:2d}/{训练轮次}: "
                      f"正常准确率={正常准确率:.4f}, 对抗准确率={对抗准确率:.4f}")

        # 最终评估
        初始对抗准确率 = 对抗准确率历史[0]
        最终对抗准确率 = 对抗准确率历史[-1]
        提升幅度 = 最终对抗准确率 - 初始对抗准确率

        print(f"\n[防御效果评估]")
        print(f"  初始对抗准确率: {初始对抗准确率:.4f}")
        print(f"  最终对抗准确率: {最终对抗准确率:.4f}")
        print(f"  正常准确率: {正常准确率历史[-1]:.4f}")
        print(f"  对抗鲁棒性提升: +{提升幅度:.4f}")
        print(f"  准确率-鲁棒性权衡: {'良好' if 正常准确率历史[-1] > 0.90 else '存在损失'}")
        print(f"  训练开销: 约为正常训练的2-3倍")

        return {
            "防御方法": "对抗训练",
            "初始对抗准确率": 初始对抗准确率,
            "最终对抗准确率": 最终对抗准确率,
            "正常准确率": 正常准确率历史[-1],
            "鲁棒性提升": 提升幅度
        }

